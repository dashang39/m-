const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('lanerc', {
  info: () => ipcRenderer.invoke('app:info'),
  listSources: () => ipcRenderer.invoke('sources:list'),
  home: (sourceId, ext) => ipcRenderer.invoke('src:home', { sourceId, ext }),
  search: (sourceId, keyword, page, ext) => ipcRenderer.invoke('src:search', { sourceId, keyword, page, ext }),
  detail: (sourceId, id, ext) => ipcRenderer.invoke('src:detail', { sourceId, id, ext }),
  categories: (sourceId) => ipcRenderer.invoke('src:categories', { sourceId }),
  filtered: (sourceId, category, filters, page) => ipcRenderer.invoke('src:filtered', { sourceId, category, filters, page }),
  health: (ids, keyword) => ipcRenderer.invoke('src:health', { ids, keyword }),
  schedule: () => ipcRenderer.invoke('schedule:fetch'),
  onHealthUpdate: (cb) => ipcRenderer.on('health:update', (_e, s) => cb(s)),
  addSite: (url) => ipcRenderer.invoke('site:add', { url }),
  probeSite: (url) => ipcRenderer.invoke('site:probe', { url }),
  removeSite: (id) => ipcRenderer.invoke('site:remove', { id }),
  importSource: (name, code) => ipcRenderer.invoke('source:import', { name, code }),
  saveCreds: (sourceId, account, password) => ipcRenderer.invoke('auth:save', { sourceId, account, password }),
  getCreds: (sourceId) => ipcRenderer.invoke('auth:has', { sourceId }),
  hasCreds: () => ipcRenderer.invoke('auth:has'),
  clearCreds: (sourceId) => ipcRenderer.invoke('auth:clear', { sourceId }),
  importSourceUrl: (url, name) => ipcRenderer.invoke('source:importUrl', { url, name }),
  deleteSource: (id) => ipcRenderer.invoke('source:delete', { id }),
  play: (sourceId, flag, ext, cacheKey) => ipcRenderer.invoke('src:play', { sourceId, flag, ext, cacheKey }),
  login: (sourceId, account, password) => ipcRenderer.invoke('src:login', { sourceId, account, password }),
  guestCaptcha: (sourceId) => ipcRenderer.invoke('src:guestCaptcha', { sourceId }),
  guestBind: (sourceId, challengeId, selected) => ipcRenderer.invoke('src:guestBind', { sourceId, challengeId, selected }),
  getStore: () => ipcRenderer.invoke('store:get'),
  saveStore: (s) => ipcRenderer.invoke('store:save', s),
  toggleFav: (item) => ipcRenderer.invoke('fav:toggle', item),
  upsertHistory: (item) => ipcRenderer.invoke('history:upsert', item),
  clearHistory: () => ipcRenderer.invoke('history:clear'),
  saveSettings: (s) => ipcRenderer.invoke('settings:save', s),
  saveBg: (dataUrl) => ipcRenderer.invoke('bg:save', dataUrl),
  toggleFullScreen: () => ipcRenderer.invoke('win:fullscreen'),
  exitFullScreen: () => ipcRenderer.invoke('win:fs-exit'),
  winMin: () => ipcRenderer.send('win:min'),
  winMax: () => ipcRenderer.send('win:max'),
  winClose: () => ipcRenderer.send('win:close'),
  isMax: () => ipcRenderer.invoke('win:isMax'),
  onWinState: (cb) => ipcRenderer.on('win:state', (_e, s) => cb(s)),
  logToMain: (level, msg) => ipcRenderer.send('log:renderer', { level, msg }),
  exportDiag: () => ipcRenderer.invoke('diag:export'),
  exportDiagQuiet: () => ipcRenderer.invoke('diag:exportQuiet'),
  pickDir: () => ipcRenderer.invoke('dialog:pickDir'),
  openLogDir: () => ipcRenderer.invoke('log:open')
});
